ALTER TABLE public.duos ENABLE ROW LEVEL SECURITY;

-- Policy 1: Anyone can read duo records (for leaderboard)
CREATE POLICY "Public Duos Read Access"
  ON public.duos
  FOR SELECT
  USING (true);

-- Policy 2: Admin can create duo pairings
CREATE POLICY "Public Duos Insert Access"
  ON public.duos
  FOR INSERT
  WITH CHECK (true);

-- Policy 3: Admin can update duo records & marks
CREATE POLICY "Public Duos Update Access"
  ON public.duos
  FOR UPDATE
  USING (true)
  WITH CHECK (true);

-- Policy 4: Admin can delete duo records
CREATE POLICY "Public Duos Delete Access"
  ON public.duos
  FOR DELETE
  USING (true);

